import { _electron as electron } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';

const root = await fs.mkdtemp(path.join(await fs.realpath(os.tmpdir()), 'xh-tool008-names-'));
const profile = await fs.mkdtemp(path.join(await fs.realpath(os.tmpdir()), 'xh-tool008-profile-'));
const app = await electron.launch({ args: ['.', '--test-hidden'], env: { ...process.env, XINGHAI_TEST_PROFILE: profile }, executablePath: process.env.XH_ELECTRON_EXECUTABLE ?? 'node_modules/electron/dist/electron.exe' });
try {
  const page = await app.firstWindow();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 900));
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }); }, root);
  await page.getByRole('button', { name: '新建项目', exact: true }).click();
  await page.getByRole('button', { name: '重命名项目' }).waitFor({ timeout: 10000 }).catch(async () => {
    console.log('CREATE DIAGNOSTIC', await page.locator('#workshop-message').textContent(), await page.locator('#project-workspace').innerText(), errors);
    throw Error('创建项目后未显示重命名入口');
  });
  await page.getByRole('button', { name: '重命名项目' }).click();
  await page.getByRole('dialog').getByRole('textbox', { name: '项目名称' }).fill('墓穴资产组');
  await page.getByRole('dialog').getByRole('button', { name: '确定' }).click();
  await page.getByRole('button', { name: '新建场景' }).click();
  await page.locator('.scene-entry').getByRole('button', { name: '改名' }).click();
  await page.getByRole('dialog').getByRole('textbox', { name: '场景名称' }).fill('石柱试摆');
  await page.getByRole('dialog').getByRole('button', { name: '确定' }).click();
  await page.getByRole('button', { name: '新建空草稿' }).click();
  await page.locator('#module-name').waitFor();
  assert.match(await page.locator('#module-name').inputValue(), /^新模块/);
  const view = await page.locator('#editview canvas').boundingBox();
  await page.mouse.click(view.x + view.width / 2, view.y + view.height / 2);
  await page.getByText('体素 1', { exact: true }).waitFor();
  await page.locator('[data-workspace="project"]').click();
  await page.locator('.module-card').getByRole('button', { name: '改名' }).click();
  await page.getByRole('dialog').getByRole('textbox', { name: '资产名称' }).fill('石柱 A');
  await page.getByRole('dialog').getByRole('button', { name: '确定' }).click();
  await page.getByRole('button', { name: '新建空草稿' }).click();
  await page.locator('[data-workspace="project"]').click();
  await page.locator('.module-card').filter({ hasText: '新模块' }).getByRole('button', { name: '移入回收区' }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认移入回收区' }).click();
  await page.locator('.module-card').filter({ hasText: '新模块' }).waitFor({ state: 'detached' });
  assert.equal(await page.locator('.module-card').count(), 1);
  await page.getByRole('button', { name: '打开项目', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '取消' }).click();
  assert.equal(await page.locator('.module-card').count(), 1);
  await page.getByRole('button', { name: '保存项目' }).click();
  await page.getByText('草稿已保存', { exact: true }).waitFor();
  const project = JSON.parse(await fs.readFile(path.join(root, 'project.xhproject.json'), 'utf8'));
  assert.equal(project.name, '墓穴资产组');
  assert.equal(project.scenes[0].name, '石柱试摆');
  const scene = JSON.parse(await fs.readFile(path.join(root, project.scenes[0].source), 'utf8'));
  assert.equal(scene.name, '石柱试摆');
  const asset = JSON.parse(await fs.readFile(path.join(root, 'scenes', scene.sceneId, scene.assets[0].source), 'utf8'));
  assert.equal(asset.name, '石柱 A');
  assert.equal(scene.assets.length, 1);
  await page.getByRole('searchbox', { name: '搜索当前场景资产' }).fill('不存在');
  assert.equal(await page.locator('.module-card:visible').count(), 0);
  await page.getByRole('searchbox', { name: '搜索当前场景资产' }).fill('石柱');
  await page.getByRole('button', { name: '列表视图' }).click();
  assert.equal(await page.locator('.asset-grid.list-view .module-card:visible').count(), 1);
  await page.getByRole('button', { name: '卡片视图' }).click();
  await page.locator('.module-card').getByRole('button', { name: '移入回收区' }).click({ timeout: 1000 });
  await page.getByRole('dialog').getByRole('button', { name: '确认移入回收区' }).click();
  await page.locator('.module-card').waitFor({ state: 'detached' });
  await page.locator('.project-trash summary').click();
  await page.locator('.trash-entry').filter({ hasText: '石柱 A' }).getByRole('button', { name: '恢复' }).click();
  await page.locator('.module-card h3').getByText('石柱 A', { exact: true }).waitFor();
  await page.locator('.scene-entry').getByRole('button', { name: '移入回收区' }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认移入回收区' }).click();
  await page.locator('.scene-entry').waitFor({ state: 'detached' });
  await page.locator('.project-trash summary').click();
  await page.locator('.trash-entry').filter({ hasText: '石柱试摆' }).getByRole('button', { name: '恢复' }).click();
  await page.locator('.module-card h3').getByText('石柱 A', { exact: true }).waitFor();
  await fs.mkdir('validation/tool008', { recursive: true });
  await page.screenshot({ path: 'validation/tool008/project-management-1440.png' });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1000, 700));
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({ path: 'validation/tool008/project-management-1000.png' });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1920, 1080));
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({ path: 'validation/tool008/project-management-1920.png' });
  await page.reload();
  if (!(await page.locator('.recent-projects').evaluate((element) => element.open)))
    await page.locator('.recent-projects summary').click();
  await page.getByText('墓穴资产组', { exact: true }).first().waitFor();
  await page.locator('.recent-project').filter({ hasText: '墓穴资产组' }).getByRole('button', { name: '打开', exact: true }).click();
  await page.locator('.module-card h3').getByText('石柱 A', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('TOOL-008 rename/recent Electron flow passed', root);
} finally {
  await app.evaluate(({ app }) => app.exit(0)).catch(() => {});
  await app.close().catch(() => {});
  await fs.rm(root, { recursive: true, force: true });
  await fs.rm(profile, { recursive: true, force: true });
}
